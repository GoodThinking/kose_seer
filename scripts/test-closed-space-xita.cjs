'use strict';
// Real managers and temporary SQLite; never touches player databases.
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
if (!process.argv[2]) throw new Error('Usage: node test-closed-space-xita.cjs <app>');
const app = path.resolve(process.argv[2]); process.chdir(app);
const load = file => require(path.join(app, 'dist', file));
load('DataBase/loaders/DataLoader');
const { Logger, LogLevel } = load('shared/utils/Logger'); Logger.SetMinLevel(LogLevel.Error);
const { Config } = load('shared/config/ServerConfig');
const { ConfigLoader } = load('shared/config/ConfigLoader');
const { ConfigRegistry } = load('shared/config/ConfigRegistry');
const { ConfigKeys, ConfigPaths, ConfigType } = load('shared/config/ConfigDefinitions');
const { DatabaseManager } = load('DataBase/DatabaseManager');
const { DatabaseHelper } = load('DataBase/DatabaseHelper');
const { DataCache } = load('DataBase/cache/DataCache');
const { PlayerData } = load('DataBase/models/PlayerData');
const { PlayerInstance } = load('GameServer/Game/Player/PlayerInstance');
const { PetManager } = load('GameServer/Game/Pet/PetManager');
const { ItemManager } = load('GameServer/Game/Item/ItemManager');
const { MapSpawnManager } = load('GameServer/Game/Map/MapSpawnManager');
const { BattleManager } = load('GameServer/Game/Battle/BattleManager');
const { GameEventBus } = load('GameServer/Game/Event/GameEventBus');
const { PetCalculator } = load('GameServer/Game/Pet/PetCalculator');
const { SptSystem } = load('GameServer/Game/Pet/SptSystem');
const { createDefaultPlayerInfo } = load('shared/models/PlayerModel');
const { createDefaultPetInfo } = load('shared/models/PetModel');
const { ChallengeBossHandler } = load('GameServer/Server/Packet/Recv/Battle/ChallengeBossHandler');
const { Count } = load('GameServer/Game/Battle/ClosedSpaceXita');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'xita-capture-'));
const db = DatabaseManager.Instance, helper = DatabaseHelper.Instance;
let originalConnection, player, reloaded;
(async () => {
  ConfigLoader.Instance._configDir = path.join(app, 'config'); ConfigLoader.Instance.Reload();
  Config.Config.database = { type: 'sqlite', path: path.join(tmp, 'test.sqlite') };
  Config.Game.clientProtocol = 'kose';
  for (const key of [ConfigKeys.PET_CONFIG, ConfigKeys.SKILL_CONFIG, ConfigKeys.SPT_CONFIG, ConfigKeys.ITEM_CONFIG]) ConfigRegistry.Instance.Register(key, ConfigPaths[key], ConfigType.XML);
  for (const key of [ConfigKeys.NATURES_CONFIG, ConfigKeys.MAP_OGRES, ConfigKeys.BOSS_ABILITIES, ConfigKeys.PET_ABILITIES, ConfigKeys.ELEMENTS_CONFIG]) if (key) ConfigRegistry.Instance.Register(key, ConfigPaths[key], ConfigType.JSON);
  await ConfigRegistry.Instance.Initialize(); await db.Initialize();
  await db.Execute('CREATE TABLE players(user_id INTEGER PRIMARY KEY, coins INTEGER NOT NULL, gold INTEGER NOT NULL, allocatable_exp INTEGER NOT NULL, pet_all_num INTEGER NOT NULL, pet_max_lev INTEGER NOT NULL)');
  await db.Execute(new (load('DataBase/migrations/scripts/012_fix_all_tables').Migration012FixAllTables)().upSQLite().find(sql => sql.startsWith('CREATE TABLE IF NOT EXISTS player_pets')));
  for (const sql of new (load('DataBase/migrations/scripts/006_create_items').Migration006CreateItems)().upSQLite()) await db.Execute(sql);
  await db.Execute('CREATE TABLE receiver_claims(owner_id INTEGER NOT NULL,reward_key TEXT NOT NULL,period_start INTEGER NOT NULL,claimed_at INTEGER NOT NULL,amount INTEGER NOT NULL,PRIMARY KEY(owner_id,reward_key,period_start))');
  const uid = 417123, packets = [], events = [];
  await db.Execute('INSERT INTO players VALUES (?,100,7,123,1,40)', [uid]);
  player = Object.create(PlayerInstance.prototype);
  Object.assign(player, { Uid: uid, Data: new PlayerData(Object.assign(createDefaultPlayerInfo(uid, 'XitaRegression'), { coins: 100, gold: 7, allocatableExp: 123, mapID: 306 })),
    EventBus: new GameEventBus(), SendPacket: async p => packets.push({ command: p.getCmdId(), result: p.getResult() }) });
  player._session = { Player: player, Socket: { destroyed: false } };
  player.PetManager = new PetManager(player); player.ItemManager = new ItemManager(player);
  player.MapSpawnManager = new MapSpawnManager(player); player.BattleManager = new BattleManager(player);
  await player.PetManager.Initialize(); await player.ItemManager.Initialize();
  const starter = Object.assign(createDefaultPetInfo(uid, 7), { level: 40, catchTime: 1950000000, isInBag: true, isDefault: true, skillArray: [10001] });
  PetCalculator.UpdatePetStats(starter); player.PetManager.PetData.PetList = [starter];
  await helper.SavePetData(player.PetManager.PetData, true); await helper.SaveItemData(player.ItemManager.ItemData, true);
  player.EventBus.On('pet:obtained', event => events.push(event));
  const saved = async () => {
    const [row] = await db.Query('SELECT pet_list FROM player_pets WHERE owner_id=?', [uid]);
    const [stats] = await db.Query('SELECT pet_all_num, pet_max_lev FROM players WHERE user_id=?', [uid]);
    return { pets: JSON.parse(row.pet_list), stats, count: await Count(player) };
  };
  const challenge = async () => { packets.length = 0; await new ChallengeBossHandler().Handle(player.Session, {}, Buffer.alloc(4)); return packets.find(p => p.command === 2411); };
  assert.equal(await Count(player), 0);
  assert.equal((await challenge()).result, 0);
  const battle = player.BattleManager.GetCurrentBattle();
  assert.equal(battle.enemy.id, 59); assert.equal(battle.enemy.level, 18);
  assert.equal(await Count(player), 0); // Starting a challenge alone does not consume the receipt.
  const service = player.BattleManager._rewardService;
  const before = await saved(); originalConnection = db.WithConnection;
  let injected = true;
  db.WithConnection = function(work) { return originalConnection.call(db, driver => work(new Proxy(driver, { get(target, key) {
    if (key === 'execute') return async (sql, args) => { const result = await target.execute(sql, args); if (injected && sql.startsWith('INSERT INTO receiver_claims')) { injected = false; throw new Error('injected failure'); } return result; };
    const value = target[key]; return typeof value === 'function' ? value.bind(target) : value;
  }}))); };
  assert.equal(await service.ProcessCatch(uid, battle, 1950000001, 306, -1), false);
  db.WithConnection = originalConnection;
  assert.deepEqual(await saved(), before); assert.equal(player.PetManager.PetData.PetList.length, 1); assert.equal(events.length, 0);
  const [a, b] = await Promise.all([service.ProcessCatch(uid, battle, 1950000001, 306, -1), service.ProcessCatch(uid, battle, 1950000002, 306, -1)]);
  assert.equal(Number(a) + Number(b), 1);
  let state = await saved(); assert.equal(state.count, 1); assert.equal(state.pets.length, 2);
  const captured = state.pets[1]; assert.equal(captured.petId, 59); assert.equal(captured.level, 18);
  assert.ok([1950000001, 1950000002].includes(captured.catchTime));
  const calculated = PetCalculator.CalculateStatsFromPet(captured);
  assert.equal(captured.maxHp, calculated.maxHp); assert.equal(captured.hp, Math.min(20, captured.maxHp));
  assert.deepEqual(captured.skillArray, SptSystem.GetDefaultSkills(59, 18).slice(0, 4).map(skill => skill.id));
  assert.deepEqual(state.stats, { pet_all_num: 2, pet_max_lev: 40 }); assert.equal(events.length, 1);
  player.BattleManager.CleanupBattle(); assert.equal((await challenge()).result, 5001);
  const oldPetData = player.PetManager.PetData;
  clearTimeout(oldPetData._saveTimer);
  clearTimeout(DataCache.Instance.Get('player', uid)?._saveTimer);
  helper.RemoveCache(uid); reloaded = new PetManager(player); await reloaded.Initialize();
  assert.deepEqual(reloaded.PetData.PetList, state.pets); assert.equal(await Count({ Uid: uid }), 1);
  player.PetManager = reloaded;
  const now = Date.now; Date.now = () => now() + 86400 * 3000;
  try { assert.equal(await Count({ Uid: uid }), 1); } finally { Date.now = now; }
  player.Data.mapID = 307; assert.equal((await challenge()).result, 0);
  const other = player.BattleManager.GetCurrentBattle(); assert.equal(other.enemy.id, 59); assert.equal(other.enemy.level, 18);
  assert.equal(await service.ProcessCatch(uid, other, 1950000003, 307, -1), true);
  state = await saved(); assert.equal(state.count, 1); assert.equal(state.pets.length, 3);
  assert.equal(state.pets[2].petId, 59); assert.equal(state.pets[2].level, 18); assert.equal(state.pets[2].catchTime, 1950000003);
  console.log('Closed-space Xita real challenge, pet storage and SQLite transaction passed');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (originalConnection) db.WithConnection = originalConnection;
  for (const data of [player?.Data, player?.PetManager?.PetData, player?.ItemManager?.ItemData, reloaded?.PetData, player && DataCache.Instance.Get('player', player.Uid)]) clearTimeout(data?._saveTimer);
  await db.Shutdown(); fs.rmSync(tmp, { recursive: true, force: true });
});
