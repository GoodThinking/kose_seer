'use strict';
// Real managers, packet handlers and temporary SQLite; defeated-team fixtures are not native gameplay proof.
// Usage: node scripts/test-king-tower.cjs <isolated runtime app>
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const app = path.resolve(process.argv[2]);
process.chdir(app);
const load = file => require(path.join(app, 'dist', file));
load('DataBase/loaders/DataLoader');
const {Logger, LogLevel} = load('shared/utils/Logger');
Logger.SetMinLevel(LogLevel.Error);
const {Config} = load('shared/config/ServerConfig');
const {ConfigLoader} = load('shared/config/ConfigLoader');
const {ConfigRegistry} = load('shared/config/ConfigRegistry');
const {ConfigKeys, ConfigPaths, ConfigType} = load('shared/config/ConfigDefinitions');
const {SkillEffectsConfig} = load('shared/config/game/SkillEffectsConfig');
const {DatabaseManager} = load('DataBase/DatabaseManager');
const {DatabaseHelper} = load('DataBase/DatabaseHelper');
const {PlayerRepository} = load('DataBase/repositories/Player/PlayerRepository');
const {PlayerData} = load('DataBase/models/PlayerData');
const {PlayerInstance} = load('GameServer/Game/Player/PlayerInstance');
const {PetManager} = load('GameServer/Game/Pet/PetManager');
const {ItemManager} = load('GameServer/Game/Item/ItemManager');
const {MapSpawnManager} = load('GameServer/Game/Map/MapSpawnManager');
const {MapActionManager} = load('GameServer/Game/Map/MapActionManager');
const {OnlineTracker} = load('GameServer/Game/Player/OnlineTracker');
const {BattleManager} = load('GameServer/Game/Battle/BattleManager');
const {ChallengeProgressManager} = load('GameServer/Game/Challenge/ChallengeProgressManager');
const {TaskManager} = load('GameServer/Game/Task/TaskManager');
const {TaskConfig} = load('shared/config/game/TaskConfig');
const {GameEventBus} = load('GameServer/Game/Event/GameEventBus');
const {ItemGainSource, BattleEventType} = load('GameServer/Game/Event/EventTypes');
const {createDefaultPetInfo} = load('shared/models/PetModel');
const {createDefaultPlayerInfo} = load('shared/models/PlayerModel');
const {PetCalculator} = load('GameServer/Game/Pet/PetCalculator');
const {CommandID} = load('shared/protocol/CommandID');
const {KingTowerChoiceHandler, KingTowerStartHandler, KingTowerSetTitleHandler} = load('GameServer/Server/Packet/Recv/Map/KingTowerHandler');
const {AchieveTitleListHandler} = load('GameServer/Server/Packet/Recv/Battle/ArenaHandlers');
const towerPath = path.join(app, 'dist/GameServer/Game/Map/KingTower.js');
let tower = require(towerPath);
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'kose-king-tower-'));
const db = DatabaseManager.Instance, helper = DatabaseHelper.Instance;
let player;
(async () => {
  ConfigLoader.Instance._configDir = path.join(app, 'config');
  ConfigLoader.Instance.Reload();
  Config.Config.database = {type: 'sqlite', path: path.join(temporary, 'king.sqlite')};
  Config.Game.clientProtocol = 'kose';
  for (const key of [ConfigKeys.PET_CONFIG, ConfigKeys.SKILL_CONFIG, ConfigKeys.SPT_CONFIG, ConfigKeys.ITEM_CONFIG]) ConfigRegistry.Instance.Register(key, ConfigPaths[key], ConfigType.XML);
  for (const key of [ConfigKeys.NATURES_CONFIG, ConfigKeys.MAP_OGRES, ConfigKeys.BOSS_ABILITIES, ConfigKeys.PET_ABILITIES, ConfigKeys.ELEMENTS_CONFIG, ConfigKeys.SKILL_EFFECTS_V2, ConfigKeys.TASK_CONFIG, ConfigKeys.UNIQUE_ITEMS_CONFIG]) if (key) ConfigRegistry.Instance.Register(key, ConfigPaths[key], ConfigType.JSON);
  await ConfigRegistry.Instance.Initialize();
  await SkillEffectsConfig.Instance.Load();
  TaskConfig.Instance.Load();
  await db.Initialize();
  await db.Execute('CREATE TABLE players(user_id INTEGER PRIMARY KEY,coins INTEGER NOT NULL,gold INTEGER NOT NULL,allocatable_exp INTEGER NOT NULL,pet_all_num INTEGER NOT NULL,pet_max_lev INTEGER NOT NULL,cur_title INTEGER NOT NULL DEFAULT 0)');
  await db.Execute('CREATE TABLE receiver_claims(owner_id INTEGER NOT NULL,reward_key TEXT NOT NULL,period_start INTEGER NOT NULL,claimed_at INTEGER NOT NULL,amount INTEGER NOT NULL,PRIMARY KEY(owner_id,reward_key,period_start))');
  const petSQL = new (load('DataBase/migrations/scripts/012_fix_all_tables').Migration012FixAllTables)().upSQLite().find(sql => sql.startsWith('CREATE TABLE IF NOT EXISTS player_pets'));
  await db.Execute(petSQL);
  const taskSQL = new (load('DataBase/migrations/scripts/012_fix_all_tables').Migration012FixAllTables)().upSQLite().find(sql => sql.startsWith('CREATE TABLE IF NOT EXISTS player_tasks'));
  await db.Execute(taskSQL);
  for (const sql of new (load('DataBase/migrations/scripts/006_create_items').Migration006CreateItems)().upSQLite()) await db.Execute(sql);
  for (const sql of new (load('DataBase/migrations/scripts/018_create_challenge_progress_table').Migration018CreateChallengeProgressTable)().upSQLite()) await db.Execute(sql);
  for (const sql of new (load('DataBase/migrations/scripts/022_create_reward_boosts').Migration022CreateRewardBoosts)().upSQLite()) await db.Execute(sql);
  const uid = 417076, now = Math.floor(Date.now() / 1000), packets = [], results = [], battleEnds = [];
  await db.Execute('INSERT INTO players VALUES (?,50000,7,123,3,100,0)', [uid]);
  player = Object.create(PlayerInstance.prototype);
  Object.assign(player, {Uid: uid, Data: new PlayerData(Object.assign(createDefaultPlayerInfo(uid, 'KingTower'), {coins: 50000, mapID: 465, superNono: 1})),
    EventBus: new GameEventBus(), SendPacket: async packet => { packets.push({command: packet.getCmdId(), result: packet.getResult(), body: packet.serialize('kose')}); }});
  player._playerRepo = new PlayerRepository();
  player._session = {UserID: uid, Socket: {destroyed: false}, Player: player};
  player.EventBus.On(BattleEventType.BATTLE_END, async event => {battleEnds.push(event);});
  player.ChallengeProgressManager = new ChallengeProgressManager(player);
  await player.ChallengeProgressManager.Initialize();
  player.TaskManager = new TaskManager(player);
  await player.TaskManager.Initialize();
  player.PetManager = new PetManager(player);
  player.ItemManager = new ItemManager(player);
  player.MapSpawnManager = new MapSpawnManager(player);
  player.BattleManager = new BattleManager(player);
  await player.PetManager.Initialize();
  await player.ItemManager.Initialize();
  const pets = [70,71,72].map((id, index) => {
    const pet = Object.assign(createDefaultPetInfo(uid, id), {level: 100, catchTime: now - 100 + index, isInBag: true, isDefault: index === 0, skillArray: [10006]});
    PetCalculator.UpdatePetStats(pet);
    return pet;
  });
  player.PetManager.PetData.PetList = pets;
  await helper.SavePetData(player.PetManager.PetData, true);
  const itemCount = id => player.ItemManager.GetItemCount(id);
  const savedCurrent = async mode => {
    const rows = await db.Query('SELECT amount FROM receiver_claims WHERE owner_id=? AND reward_key=? AND period_start=0', [uid, 'king:tower:' + mode + ':current']);
    return rows[0]?.amount || 0;
  };
  const defeated = context => ({kingTower: context, enemyTeam: context.definition.pets.map(id => ({id, hp: 0}))});
  const clearFloor = async () => {
    const context = await tower.PrepareKingTowerBattle(player);
    return {context, state: await tower.AdvanceKingTower(player, defeated(context), () => true)};
  };

  await assert.rejects(tower.EnterKingTower(player, 1, 2), tower.KingTowerError);
  await assert.rejects(tower.EnterKingTower(player, 2, 1), tower.KingTowerError);
  const initial = await tower.GetKingTowerProgress(player);
  assert.equal(initial.normalMax, 0);
  assert.equal(initial.activeMode, 0);
  const titleBody = Buffer.alloc(4); titleBody.writeUInt32BE(38);
  await new KingTowerSetTitleHandler().Handle(player.Session, {}, titleBody);
  assert.equal((await db.Query('SELECT cur_title FROM players WHERE user_id=?', [uid]))[0].cur_title, 0, 'unearned title cannot be equipped');
  results.push('Locked checkpoints, extreme prerequisites and unearned title are rejected without changing saved progress');

  player.MapActionManager = new MapActionManager(player);
  OnlineTracker.Instance.PlayerLogin(uid, player.Session);
  OnlineTracker.Instance.UpdatePlayerMap(uid, 465, 0, player.Data.posX, player.Data.posY);
  const entrancePosition = {x: player.Data.posX, y: player.Data.posY};
  const entryBody = Buffer.alloc(8);
  entryBody.writeUInt32BE(1, 0);
  entryBody.writeUInt32BE(1, 4);
  packets.length = 0;
  await new KingTowerChoiceHandler().Handle(player.Session, {}, entryBody);
  assert.equal(packets.some(packet => packet.command === CommandID.LEAVE_MAP), false, 'private entry must not spoof the native leave acknowledgement and restart the public map');
  assert.equal(OnlineTracker.Instance.GetPlayerMap(uid), 0, 'private challenge leaves public map membership');
  assert.equal(OnlineTracker.Instance.GetPlayersInMap(465).includes(uid), false, 'public player lists do not retain a tower ghost');
  await player.MapActionManager.HandlePeopleWalk({walkType: 0, x: 829, y: 116, amfData: Buffer.alloc(0)});
  assert.deepEqual({x: player.Data.posX, y: player.Data.posY}, entrancePosition, 'private floor movement cannot overwrite the saved entrance position');
  assert.equal(OnlineTracker.Instance.GetPlayerMap(uid), 0, 'private movement cannot rejoin the public entrance');
  results.push('Native entry removes public membership; private walking preserves entrance coordinates and cannot recreate a public ghost');
  packets.length = 0;
  await new KingTowerStartHandler().Handle(player.Session, {}, Buffer.alloc(0));
  await player.BattleManager.HandleEscapeFight();
  assert.equal(player.BattleManager.GetCurrentBattle(), null);
  assert.equal(await savedCurrent(1), 0, 'escape preserves the current uncleared floor');
  const escaped = packets.find(packet => packet.command === CommandID.FIGHT_OVER);
  assert.equal(escaped.body.readUInt32BE(0), 1, 'current native protocol identifies escape with reason1');
  assert.equal(battleEnds.length, 0, 'escape never completes battle objectives');
  await new KingTowerStartHandler().Handle(player.Session, {}, Buffer.alloc(0));
  const battle = player.BattleManager.GetCurrentBattle();
  assert.ok(battle, 'real battle starts');
  battle.player.battleLevels = [2,1,0,0,0,0];
  battle.player.statusDurations[2] = 3;
  battle.player.skillPP[0] = 7;
  const originalPlayer = battle.player;
  battle.enemy.hp = 0;
  battle.isOver = true;
  packets.length = 0;
  await player.BattleManager.HandleFightOver(uid, 0);
  assert.equal(player.BattleManager.GetCurrentBattle(), battle, 'first defeated foe does not finish the battle');
  assert.equal(battle.player, originalPlayer, 'same player combat state survives enemy replacement');
  assert.deepEqual(battle.player.battleLevels, [2,1,0,0,0,0]);
  assert.equal(battle.player.statusDurations[2], 3);
  assert.equal(battle.player.skillPP[0], 7);
  assert.equal(battle.isOver, false, 'next turn remains playable');
  assert.equal(await savedCurrent(1), 0, 'partial team grants no floor progress');
  assert.equal(packets.some(packet => packet.command === CommandID.FIGHT_OVER), false, 'no premature fight-over notification');
  assert.equal(battleEnds.length, 0, 'partial team does not complete battle objectives');
  const changedEnemy = packets.find(packet => packet.command === CommandID.CHANGE_PET);
  assert.equal(changedEnemy.body.readUInt32BE(0), 0, 'native replacement belongs to enemy side');
  assert.equal(changedEnemy.body.readUInt32BE(4), 67, 'second opponent becomes active');
  await assert.rejects(tower.AdvanceKingTower(player, battle, () => true), /defeated complete team/);
  battle.enemy.hp = 0;
  battle.isOver = true;
  await player.BattleManager.HandleFightOver(uid, 0);
  assert.equal(player.BattleManager.GetCurrentBattle(), null);
  assert.equal(await savedCurrent(1), 1, 'only final enemy advances floor');
  assert.equal(battleEnds.length, 1, 'only final enemy completes one battle objective');
  assert.equal(battleEnds[0].extra.rewardStatus, 'complete', 'normal battle rewards also settle successfully');
  results.push('Real BattleManager replaces enemy via native packet, preserves boosts/status/PP and settles only after complete team defeat');

  for (let floor = 2; floor <= 9; floor++) assert.equal((await clearFloor()).state.normalCurrent, floor);
  const failedMilestone = await tower.PrepareKingTowerBattle(player);
  await db.Execute("CREATE TRIGGER king_reward_abort BEFORE UPDATE OF item_list ON player_items BEGIN SELECT RAISE(ABORT,'king reward test'); END");
  await assert.rejects(tower.AdvanceKingTower(player, defeated(failedMilestone), () => true), /king reward test/);
  assert.equal(await savedCurrent(1), 9);
  assert.equal(itemCount(400162), 0);
  assert.equal((await tower.GetKingTowerProgress(player)).achievementPoints, 0);
  await db.Execute('DROP TRIGGER king_reward_abort');
  let finalNormal;
  for (let floor = 10; floor <= 30; floor++) {
    const cleared = await clearFloor();
    assert.equal(cleared.state.normalCurrent, floor);
    if (floor === 30) finalNormal = cleared.context;
  }
  assert.equal(finalNormal.next.stage, 30, 'final reply selects terminal animation, not floor30 again');
  let progress = await tower.GetKingTowerProgress(player);
  assert.equal(progress.normalMax, 30);
  assert.equal(progress.activeMode, 0);
  assert.equal(progress.achievementPoints, 40);
  assert.equal(itemCount(400162), 1);
  assert.equal(itemCount(400181), 1);
  await assert.rejects(tower.AdvanceKingTower(player, defeated(finalNormal), () => true));
  await tower.EnterKingTower(player, 1, 1);
  for (let floor = 1; floor <= 10; floor++) await clearFloor();
  progress = await tower.GetKingTowerProgress(player);
  assert.equal(progress.normalMax, 30, 'replay preserves best record');
  assert.equal(progress.achievementPoints, 40);
  assert.equal(itemCount(400162), 1, 'replay never duplicates essence');
  results.push('Normal30 terminal state, both essences, first-clear points, verified SQL rollback and replay uniqueness persist in SQLite');

  pets[2].isInBag = false;
  await assert.rejects(tower.EnterKingTower(player, 2, 1), tower.KingTowerError);
  pets[2].isInBag = true;
  assert.equal(await player.ItemManager.GiveItem(100591, 1, ItemGainSource.DROP), true);
  await tower.EnterKingTower(player, 2, 1);
  const reserve = Object.assign(createDefaultPetInfo(uid, 73), {level: 100, catchTime: now + 10, isInBag: true});
  PetCalculator.UpdatePetStats(reserve);
  pets[2].isInBag = false;
  player.PetManager.PetData.PetList = [...pets, reserve];
  await assert.rejects(tower.PrepareKingTowerBattle(player), tower.KingTowerError);
  pets[2].isInBag = true;
  reserve.isInBag = false;
  for (let floor = 1; floor <= 5; floor++) await clearFloor();
  delete require.cache[require.resolve(towerPath)];
  tower = require(towerPath);
  await assert.rejects(tower.PrepareKingTowerBattle(player), tower.KingTowerError);
  progress = await tower.GetKingTowerProgress(player);
  assert.equal(progress.heroCurrent, 5);
  assert.equal(progress.activeMode, 2);
  await tower.EnterKingTower(player, 2, 0);
  assert.equal((await tower.PrepareKingTowerBattle(player)).floor, 6, 'cold service state resumes saved floor');
  for (let floor = 6; floor <= 10; floor++) await clearFloor();
  progress = await tower.GetKingTowerProgress(player);
  assert.equal(progress.heroMax, 10);
  assert.equal(progress.activeMode, 0, 'extreme ten-floor segment returns to entrance');
  assert.equal(progress.achievementPoints, 55);
  for (const id of [100591,100592,100593,100594,100595]) assert.equal(itemCount(id), 1);
  await assert.rejects(tower.PrepareKingTowerBattle(player), tower.KingTowerError);
  results.push('Extreme party membership, cold-service continuation, ten-floor exit and original five-piece outfit are enforced');

  assert.equal(await player.ItemManager.GiveItem(300066, 999, ItemGainSource.DROP), true);
  await tower.EnterKingTower(player, 2, 2);
  let fullReward;
  for (let floor = 11; floor <= 20; floor++) fullReward = await clearFloor();
  assert.equal(fullReward.state.heroMax, 20);
  assert.equal(fullReward.state.pendingRewards, true);
  assert.equal(itemCount(300066), 999);
  assert.equal(fullReward.state.achievementPoints, 75);
  assert.deepEqual(await tower.GetKingTowerTitles(player), [38]);
  assert.equal((await tower.GetKingTowerProgress(player)).pendingRewards, true);
  assert.equal(player.ItemManager.ConsumeItem(300066, 1), true);
  await helper.SaveItemData(player.ItemManager.ItemData, true);
  progress = await tower.GetKingTowerProgress(player);
  assert.equal(progress.pendingRewards, false);
  assert.equal(itemCount(300066), 999, 'reserved milestone item fills exactly the freed slot');
  assert.equal((await tower.GetKingTowerProgress(player)).rewardItems.length, 0, 'claim readback never grants twice');
  await new KingTowerSetTitleHandler().Handle(player.Session, {}, titleBody);
  assert.equal((await db.Query('SELECT cur_title FROM players WHERE user_id=?', [uid]))[0].cur_title, 38);
  packets.length = 0;
  await new AchieveTitleListHandler().Handle(player.Session, {}, Buffer.alloc(0));
  const titles = packets.find(packet => packet.command === 3403).body;
  assert.equal(titles.readUInt32BE(0), 1);
  assert.equal(titles.readUInt32BE(4), 38);
  results.push('Full inventory retains won floor and earned title; freeing one slot grants exactly one reserved crystal; equipped title persists');

  assert.equal(player.ItemManager.ConsumeItem(300066, 1), true);
  await helper.SaveItemData(player.ItemManager.ItemData, true);
  await tower.EnterKingTower(player, 2, 3);
  let finalHero;
  for (let floor = 21; floor <= 30; floor++) finalHero = await clearFloor();
  assert.equal(finalHero.context.next.stage, 30);
  assert.equal(finalHero.state.heroMax, 30);
  assert.equal(finalHero.state.activeMode, 0);
  assert.equal(finalHero.state.achievementPoints, 95);
  assert.equal(itemCount(300066), 999, 'floor30 has its separate one-time crystal');
  assert.deepEqual(await tower.GetKingTowerTitles(player), [38], 'no fabricated floor30 title');
  await assert.rejects(tower.AdvanceKingTower(player, defeated(finalHero.context), () => true));
  progress = await tower.GetKingTowerProgress(player);
  assert.equal(progress.rewardItems.length, 0);
  assert.equal(progress.achievementPoints, 95);
  results.push('All sixty service floor transitions terminate; extreme30 crystal is distinct and unique; achievements do not repeat');
  console.log(JSON.stringify({passed: results.length, results, database: 'temporary-only', nativeGameplayClaim: false}, null, 2));
})().catch(error => {console.error(error); process.exitCode = 1;}).finally(async () => {
  if (player) {OnlineTracker.Instance.PlayerLogout(player.Uid); player.BattleManager.CleanupBattle(); player.Data.cleanup(); helper.RemoveCache(player.Uid);}
  await db.Shutdown();
  fs.rmSync(temporary, {recursive: true, force: true});
  process.exit(process.exitCode || 0);
});
