'use strict';
// Drive real boss battles through BattleManager packets on a temporary database (never a live account).
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const app = path.resolve(process.argv[2]);
process.chdir(app);
const load = file => require(path.join(app, 'dist', file));
load('DataBase/loaders/DataLoader');
const {Logger, LogLevel} = load('shared/utils/Logger');
Logger.SetMinLevel(LogLevel.Error);
const {ChallengeBossHandler} = load('GameServer/Server/Packet/Recv/Battle/ChallengeBossHandler');
const {ChallengeProgressManager} = load('GameServer/Game/Challenge/ChallengeProgressManager');
const {PuniDoorOf} = load('GameServer/Game/Battle/PuniSealBattle');
const {Config} = load('shared/config/ServerConfig');
const {ConfigLoader} = load('shared/config/ConfigLoader');
const {ConfigRegistry} = load('shared/config/ConfigRegistry');
const {ConfigKeys, ConfigPaths, ConfigType} = load('shared/config/ConfigDefinitions');
const {DatabaseManager} = load('DataBase/DatabaseManager');
const {DatabaseHelper} = load('DataBase/DatabaseHelper');
const {PlayerData} = load('DataBase/models/PlayerData');
const {PlayerInstance} = load('GameServer/Game/Player/PlayerInstance');
const {PetManager} = load('GameServer/Game/Pet/PetManager');
const {ItemManager} = load('GameServer/Game/Item/ItemManager');
const {MapSpawnManager} = load('GameServer/Game/Map/MapSpawnManager');
const {BattleManager} = load('GameServer/Game/Battle/BattleManager');
const {GameEventBus} = load('GameServer/Game/Event/GameEventBus');
const {createDefaultPetInfo} = load('shared/models/PetModel');
const {createDefaultPlayerInfo} = load('shared/models/PlayerModel');
const {PetCalculator} = load('GameServer/Game/Pet/PetCalculator');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'kose-puni-entry-'));
const db = DatabaseManager.Instance, helper = DatabaseHelper.Instance;
let player;
(async () => {
  ConfigLoader.Instance._configDir = path.join(app, 'config');
  ConfigLoader.Instance.Reload();
  Config.Config.database = {type: 'sqlite', path: path.join(temporary, 'boss.sqlite')};
  Config.Game.clientProtocol = 'xin-20261013';
  for (const key of [ConfigKeys.PET_CONFIG, ConfigKeys.SKILL_CONFIG, ConfigKeys.SPT_CONFIG, ConfigKeys.ITEM_CONFIG]) ConfigRegistry.Instance.Register(key, ConfigPaths[key], ConfigType.XML);
  for (const key of [ConfigKeys.NATURES_CONFIG, ConfigKeys.MAP_OGRES, ConfigKeys.BOSS_ABILITIES, ConfigKeys.PET_ABILITIES, ConfigKeys.ELEMENTS_CONFIG, ConfigKeys.SKILL_EFFECTS_V2]) if (key) ConfigRegistry.Instance.Register(key, ConfigPaths[key], ConfigType.JSON);
  await ConfigRegistry.Instance.Initialize();
  await load('shared/config/game/SkillEffectsConfig').SkillEffectsConfig.Instance.Load();
  await db.Initialize();
  await db.Execute('CREATE TABLE players(user_id INTEGER PRIMARY KEY,coins INTEGER NOT NULL,gold INTEGER NOT NULL,allocatable_exp INTEGER NOT NULL,pet_all_num INTEGER NOT NULL,pet_max_lev INTEGER NOT NULL)');
  const petSQL = new (load('DataBase/migrations/scripts/012_fix_all_tables').Migration012FixAllTables)().upSQLite().find(sql => sql.startsWith('CREATE TABLE IF NOT EXISTS player_pets'));
  await db.Execute(petSQL);
  for (const sql of new (load('DataBase/migrations/scripts/006_create_items').Migration006CreateItems)().upSQLite()) await db.Execute(sql);
  for (const sql of new (load('DataBase/migrations/scripts/018_create_challenge_progress_table').Migration018CreateChallengeProgressTable)().upSQLite()) await db.Execute(sql);
  const uid = 417069, now = Math.floor(Date.now() / 1000);
  await db.Execute('INSERT INTO players VALUES (?, 10000, 7, 123, 1, 75)', [uid]);
  const packets = [];
  player = Object.create(PlayerInstance.prototype);
  Object.assign(player, {Uid: uid, Data: new PlayerData(Object.assign(createDefaultPlayerInfo(uid, 'PuniEntry'), {coins: 10000, mapID: 53})),
    EventBus: new GameEventBus(), SendPacket: async packet => {packets.push({command: packet.getCmdId(), result: packet.getResult(), body: packet.serialize('xin-20261013')});}});
  player._session = {Socket: {destroyed: false}, Player: player};
  player.ChallengeProgressManager = new ChallengeProgressManager(player);
  await player.ChallengeProgressManager.Initialize();
  player.PetManager = new PetManager(player);
  player.ItemManager = new ItemManager(player);
  player.MapSpawnManager = new MapSpawnManager(player);
  player.BattleManager = new BattleManager(player);
  await player.PetManager.Initialize();
  await player.ItemManager.Initialize();
  const pet = Object.assign(createDefaultPetInfo(uid, 70), {level: 100, catchTime: now - 100, isInBag: true, isDefault: true, skillArray: [10037]});
  PetCalculator.UpdatePetStats(pet);
  player.PetManager.PetData.PetList = [pet];
  await helper.SavePetData(player.PetManager.PetData, true);
  const handler = new ChallengeBossHandler(), results = [];
  const challenge = async (mapId, door) => {
    player.BattleManager.CleanupBattle();
    packets.length = 0;
    player.Data.mapID = mapId;
    const body = Buffer.alloc(4); body.writeUInt32BE(door);
    await handler.Handle(player._session, {}, body);
    assert.equal(player.Data.mapID, mapId, 'Local battle routing must not teleport the player');
    return {result: packets.find(p => p.command === 2411)?.result, battle: player.BattleManager.GetCurrentBattle()};
  };
  const locked = await challenge(108, 2);
  assert.equal(locked.result, 11027);
  assert.ok(!locked.battle);
  assert.ok(!player.Data.dailyResArr[41], 'Locked seals must not consume an attempt');
  const first = await challenge(108, 1);
  assert.equal(first.result, 0, 'The native local-map request must start the first seal, not fail with 5001');
  assert.equal(first.battle.bossMapId, 514);
  assert.equal(PuniDoorOf(first.battle), 1);
  assert.equal(first.battle.enemy.hp, 7000);
  assert.equal(first.battle.enemy.bossMechanics.onlyMustHit, true);
  assert.equal(player.Data.dailyResArr[40], 1);
  await player.BattleManager.HandleReadyToFight();
  first.battle.player.hp = first.battle.player.maxHp = 100000;
  first.battle.player.speed = 9999;
  const hp = first.battle.enemy.hp;
  await player.BattleManager.HandleUseSkill(10037);
  assert.ok(packets.some(packet => packet.command === 2505), 'The real first turn must produce a battle packet');
  assert.ok(first.battle.enemy.hp < hp, 'A must-hit attack must damage the actual void seal');
  results.push({door: 1, map: first.battle.bossMapId, turnDamage: hp - first.battle.enemy.hp});
  assert.equal((await challenge(108, 1)).result, 11028, 'Local-map routing must preserve daily limits');
  assert.equal((await challenge(108, 8)).result, 11027, 'True form stays locked before seven seals');
  player.ChallengeProgressManager.SetPuniLevel(7);
  for (let door = 2; door <= 8; door++) {
    const next = await challenge(108, door);
    assert.equal(next.result, 0, 'Unlocked seal ' + door);
    assert.equal(PuniDoorOf(next.battle), door);
    assert.equal(next.battle.enemy.id, 300);
    assert.equal(player.Data.dailyResArr[39 + door], 1);
    if (door === 8) {
      assert.equal(next.battle.enemy.puniState.puniLife, 0, 'True form must initialize its first of six lives');
      assert.equal(next.battle.enemy.maxHp, 7000);
    }
    results.push({door, map: next.battle.bossMapId, enemy: next.battle.enemy.name});
  }
  assert.equal((await challenge(108, 8)).result, 11028);
  const other = await challenge(53, 1);
  assert.equal(other.result, 0);
  assert.equal(other.battle.enemy.name, '魔狮迪露');
  assert.equal(other.battle.bossMapId, 53, 'Ordinary boss maps must remain unchanged');
  console.log('PUNI_ENTRY_SMOKE=' + JSON.stringify({results, lockedSeal: 11027, dailyLimit: 11028, otherBoss: other.battle.enemy.name, database: 'temporary-only'}));
})().catch(error => {console.error(error); process.exitCode = 1;}).finally(async () => {
  if (player) {player.BattleManager.CleanupBattle(); player.Data.cleanup(); helper.RemoveCache(player.Uid);}
  await db.Shutdown();
  fs.rmSync(temporary, {recursive: true, force: true});
  process.exit(process.exitCode || 0);
});
